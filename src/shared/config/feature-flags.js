// Временное скрытие разделов по флагам из window.APP_DATA.features — бэк
// инлайнит этот объект в страницу до загрузки бандла (там же живут
// contract_signing и остальные), поэтому значения доступны синхронно и
// читаются один раз на старте: смена флага в админке доезжает до вкладки
// после перезагрузки страницы.
//
// Код разделов не удаляется, только перестаёт отдаваться пользователю:
// пункт меню скрывается, роут редиректит на дашборд. Вернуть раздел =
// выставить флаг в true на бэке, правок во фронте не нужно.
//
// Отсутствующее поле трактуем как «показывать»: на контуре со старым бэком,
// который этих флагов ещё не отдаёт, поведение остаётся прежним.
const features = window?.APP_DATA?.features || {};

export const isFactoringEnabled = features.factoring ?? true;

export const isManufacturersEnabled = features.manufacturer ?? true;

export const isTenderEnabled = features.tender ?? true;
