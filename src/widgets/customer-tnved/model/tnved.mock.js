export function flattenTnvedLeaves(tree = tnvedTree) {
   const leaves = [];

   function walk(nodes) {
      nodes.forEach((node) => {
         if (!node.children || node.children.length === 0) {
            if (node.code) {
               leaves.push(node);
            }

            return;
         }

         walk(node.children);
      });
   }

   walk(tree);

   return leaves;
}
